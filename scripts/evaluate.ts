// Recommendation benchmark (spec 17.4). Writes docs/evaluation-report.md and fails if release gates are not met.
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { analyzeProject } from "../src/analyzer/index.ts";
import { recommend } from "../src/recommender/index.ts";
import { goalTags, SCORING_VERSION } from "../src/recommender/taxonomy.ts";
import { loadBundledCatalog } from "../src/sources/catalog.ts";

interface Case { id: string; category: string; project: string | null; stack?: string[]; goal: string; relevant: string[]; irrelevant: string[]; rationale: string }
const root = path.resolve(import.meta.dirname, "..");
const spec = JSON.parse(readFileSync(path.join(root, "tests/evaluations/cases.json"), "utf8")) as { labelStatus: string; cases: Case[] };
const catalog = loadBundledCatalog();
const candidates = catalog.entries.map((e) => ({ ...e, annotationOrigin: "curated" as const, discoveredVia: ["bundled"] }));
const empty = mkdtempSync(path.join(os.tmpdir(), "skillpilot-eval-"));

const rows: string[] = [];
let hitN = 0, hitD = 0, emptyOk = 0, emptyD = 0, irrelevantInTop3 = 0;
const precisions: number[] = [];
const excludedFromPrecision: string[] = [];
for (const c of spec.cases) {
  const dir = c.project ? path.join(root, "tests/fixtures/projects", c.project) : empty;
  const a = await analyzeProject(dir, { stack: c.stack, goal: c.goal, home: empty });
  const input = { candidates, stack: a.effectiveStack, goalTags: goalTags(c.goal), agents: ["claude-code", "codex"] as ("claude-code" | "codex")[] };
  const top = recommend({ ...input, limit: 5 }).recommendations.map((r) => r.id);
  const eligible = recommend({ ...input, limit: 20 }).recommendations.map((r) => r.id);
  const top3 = top.slice(0, 3);
  let outcome: string;
  if (c.relevant.length === 0) {
    emptyD++;
    const ok = top.length === 0;
    if (ok) emptyOk++;
    outcome = ok ? "empty ✓" : `expected empty, got ${top.length}`;
  } else {
    hitD++;
    const hit = top3.some((id) => c.relevant.includes(id));
    if (hit) hitN++;
    outcome = hit ? "hit ✓" : "miss ✗";
    const eligibleRelevant = c.relevant.filter((id) => eligible.includes(id)).length;
    if (eligibleRelevant >= 3) precisions.push(top3.filter((id) => c.relevant.includes(id)).length / 3);
    else excludedFromPrecision.push(c.id);
  }
  irrelevantInTop3 += top3.filter((id) => c.irrelevant.includes(id)).length;
  const short = (id: string) => id.split("/").pop();
  rows.push(`| ${c.id} | ${c.category} | ${top3.map(short).join(", ") || "—"} | ${c.relevant.map(short).join(", ") || "(empty)"} | ${outcome} |`);
}
rmSync(empty, { recursive: true, force: true });

const hitRate = hitN / hitD;
const precision = precisions.length ? precisions.reduce((s, p) => s + p, 0) / precisions.length : null;
const categories = new Set(spec.cases.map((c) => c.category));
const gates = [
  { name: "Top-3 hit rate ≥ 0.80", pass: hitRate >= 0.8 },
  { name: "Macro precision@3 ≥ 0.60 (cases with ≥3 eligible relevant entries)", pass: precision === null || precision >= 0.6 },
  { name: "≥ 20 cases", pass: spec.cases.length >= 20 },
  { name: "≥ 8 categories", pass: categories.size >= 8 },
];
const report = `# Recommendation evaluation report

Generated by \`npm run test:evaluation\`. Catalog ${catalog.catalogVersion}, scoring ${SCORING_VERSION}, ${spec.cases.length} cases in ${categories.size} categories.

**Label status:** ${spec.labelStatus}. These results are not evidence that SkillPilot finds the best skill on the internet; they measure a small curated catalog against labels written for it.

| Metric | Value |
| --- | --- |
| Top-3 hit rate | ${hitN}/${hitD} = ${hitRate.toFixed(2)} |
| Macro precision@3 | ${precision === null ? "not measurable" : precision.toFixed(2)} (${precisions.length} qualifying cases; ${excludedFromPrecision.length} excluded for having fewer than 3 eligible relevant entries) |
| Empty-result accuracy | ${emptyOk}/${emptyD} |
| Labelled-irrelevant entries appearing in a top 3 | ${irrelevantInTop3} |

## Gates

${gates.map((g) => `- ${g.pass ? "PASS" : "FAIL"} ${g.name}`).join("\n")}

## Cases

| Case | Category | Top 3 | Relevant | Outcome |
| --- | --- | --- | --- | --- |
${rows.join("\n")}

## Limitations

- Precision@3 is not measurable on catalog ${catalog.catalogVersion}: no case has three eligible relevant entries, so the precision gate is vacuous until the catalog grows.
- Labels were drafted by the implementing agent and require human maintainer review before release.
- The taxonomy and catalog tags were tuned in the same session as these labels, with no held-out set. Treat the hit rate as a regression check, not an accuracy estimate.
- Expected-relevant sets are small; a hit means one labelled entry reached the top 3, not that the list is optimal.
`;
writeFileSync(path.join(root, "docs/evaluation-report.md"), report);
console.log(report.split("## Cases")[0]);
process.exit(gates.every((g) => g.pass) ? 0 : 1);
