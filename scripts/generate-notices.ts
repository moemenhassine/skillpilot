// Writes THIRD_PARTY_NOTICES.md from the installed runtime dependencies' own license files.
// `--check` fails if the checked-in file differs (for CI).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const pkg = JSON.parse(readFileSync(path.join(ROOT, "package.json"), "utf8")) as { dependencies: Record<string, string> };
const sections = Object.keys(pkg.dependencies).sort().map((name) => {
  const dir = path.join(ROOT, "node_modules", name);
  const meta = JSON.parse(readFileSync(path.join(dir, "package.json"), "utf8")) as { version: string; license: string };
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice)/i.test(f)).sort();
  if (!files.length) throw new Error(`${name} ships no license file; add its notice by hand before release.`);
  return [`## ${name} ${meta.version} (${meta.license})`, "", ...files.flatMap((f) => ["```text", readFileSync(path.join(dir, f), "utf8").trimEnd(), "```", ""])].join("\n");
});
const out = [
  "# Third-party notices",
  "",
  "SkillPilot's distributed package includes or depends at runtime on the packages below. Their license texts are reproduced from the installed packages. Generated by `node scripts/generate-notices.ts`; do not edit by hand.",
  "",
  "SkillPilot does not redistribute any cataloged agent skill. `catalog/skills.json` records public source identifiers, upstream skill names and descriptions, and license evidence paths. Each skill remains under its own upstream license, which is not necessarily MIT; `skillpilot review` reports it per skill.",
  "",
  ...sections,
].join("\n");
const file = path.join(ROOT, "THIRD_PARTY_NOTICES.md");
if (process.argv.includes("--check")) {
  if (readFileSync(file, "utf8") !== out) { console.error("THIRD_PARTY_NOTICES.md is stale; run node scripts/generate-notices.ts"); process.exit(1); }
  console.log("THIRD_PARTY_NOTICES.md is up to date.");
} else {
  writeFileSync(file, out);
  console.log(`Wrote notices for ${sections.length} packages.`);
}
